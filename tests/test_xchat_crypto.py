MESSAGE_ID = '12345678-1234-4234-8234-123456789abc'
CONVERSATION_KEY = bytes(range(32))
NONCES = (bytes(range(32, 56)), bytes(range(64, 96)), bytes(range(96, 120)))
# Hand-encoded frontend MessageEntryHolder -> message -> MessageContents('hi').
PLAINTEXT = bytes.fromhex(
    '0c00010c00010b0001000000026869'
    '0f00020c000000000f00030c0000000008000700000001000000')
# Independently checked with Node crypto.hkdfSync/createHash over the source's
# byte concatenation (not generated by the functions under test).
MESSAGE_KEY_V1 = bytes.fromhex(
    'e0de0bdc4ef2ba652cc4036b5b29f0c7d2a0e36b3255558c06d9da1f9f74480a')
FRANKING_TAG = bytes.fromhex(
    '1b92ee0c78a25de4b5f7dd29a4d7400409ccccb06a0da963a64fd98a0c924d33')
CONTENTS_V1 = (
    'ICEiIyQlJicoKSorLC0uLzAxMjM0NTY3UdcwwB+k7HZra42+IlQfu/Ku/ihKh9wk'
    'ZxeU1ykn4CzWRG/hbu7gGs9lyMseX2HaovWfXwHp7tSU')


def unpadded_decode(value):
    if isinstance(value, bytes):
        value = value.decode('ascii')
    return base64.b64decode(value + '=' * (-len(value) % 4), validate=True)


class XChatCryptoTests(unittest.TestCase):
    def setUp(self):
        # This deliberately public synthetic scalar is never an account key.
        self.private_key = ec.derive_private_key(1, ec.SECP256R1())
        self.pem = self.private_key.private_bytes(
            serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption())
        self.keys = XChatKeyMaterial(
            sender_id='100', conversation_id='100-200',
            conversation_key=CONVERSATION_KEY, conversation_key_version=7,
            signing_key=self.pem, public_key_version='9', signature_version=11,
            contents_encryption_version=1,
            conversation_token='SYNTHETIC_CONVERSATION_TOKEN',
        )

    def prepare(self, keys=None, text='hi', message_id=MESSAGE_ID):
        with patch('utils.xchat_crypto.os.urandom', side_effect=NONCES) as random:
            result = prepare_text_message(text, keys or self.keys, message_id=message_id)
        self.assertEqual([call.args for call in random.call_args_list], [(24,), (32,), (24,)])
        return result

    def unpack(self, prepared):
        return (decode_base64_struct(prepared.encoded_message_create_event),
                decode_base64_struct(prepared.encoded_message_event_signature))

    def verify(self, signature, payload):
        raw = unpadded_decode(field(signature, 1, 11))
        self.assertEqual(len(raw), 64)
        der = encode_dss_signature(int.from_bytes(raw[:32], 'big'),
                                   int.from_bytes(raw[32:], 'big'))
        self.private_key.public_key().verify(der, payload, ec.ECDSA(hashes.SHA256()))

    def test_v1_encryption_matches_golden_plaintext_and_derived_key(self):
        prepared = self.prepare()
        event, signature = self.unpack(prepared)
        ciphertext = field(event, 100, 11)
        self.assertEqual(base64.b64encode(ciphertext).decode().rstrip('='), CONTENTS_V1)
        self.assertEqual(SecretBox(MESSAGE_KEY_V1).decrypt(ciphertext), PLAINTEXT)
        with self.assertRaises(CryptoError):
            SecretBox(CONVERSATION_KEY).decrypt(ciphertext)
        self.assertEqual(field(event, 101, 11), b'7')
        self.assertIs(field(event, 102, 2), True)
        self.assertIs(field(event, 105, 2), False)
        self.assertEqual(field(event, 106, 8), 1)
        self.assertEqual(field(event, 112, 6), 1)
        self.assertEqual(field(signature, 2, 11), b'9')
        self.assertEqual(field(signature, 3, 11), b'11')
        self.assertNotIn(4, signature)
        member_kind, members = field(signature, 5, 15)
        self.assertEqual(member_kind, 12)
        self.assertEqual(members, [{1: (11, b'100'), 2: (11, b'9')}])

    def test_franking_matches_independent_golden_vector(self):
        event, _ = self.unpack(self.prepare())
        franking = field(event, 108, 12)
        self.assertEqual(field(franking, 1, 11), FRANKING_TAG)
        self.assertEqual(SecretBox(CONVERSATION_KEY).decrypt(field(franking, 2, 11)), NONCES[1])
        self.assertNotIn(4, franking)  # no media hashes

    def test_signature_payload_uses_standard_unpadded_base64(self):
        _, signature = self.unpack(self.prepare())
        payload = (
            'MessageCreateEvent,' + MESSAGE_ID + ',100,100-200,7,'
            + CONTENTS_V1 + ',1,signature_version=11').encode()
        self.verify(signature, payload)
        self.assertNotIn(b'=', field(signature, 1, 11))
        self.assertIn('+', CONTENTS_V1)
        self.assertIn('/', CONTENTS_V1)
        # Confusing the second encodeAsBase64 argument with URL-safe mode was
        # a plausible regression; the captured frontend uses padding mode.
        with self.assertRaises(InvalidSignature):
            self.verify(signature, payload.replace(b'+', b'-').replace(b'/', b'_'))

    def test_signature_version_branches_are_verified(self):
        for version in range(1, 12):
            with self.subTest(version=version):
                _, signature = self.unpack(self.prepare(replace(self.keys, signature_version=version)))
                if version == 1:
                    payload = f'{MESSAGE_ID},100,100-200,{CONTENTS_V1}'
                else:
                    payload = f'MessageCreateEvent,{MESSAGE_ID},100,100-200,7,{CONTENTS_V1}'
                    if version >= 10:
                        payload += ',1'
                    if version >= 9:
                        payload += f',signature_version={version}'
                self.verify(signature, payload.encode())

    def test_original_encryption_uses_conversation_key_and_signed_null(self):
        event, signature = self.unpack(self.prepare(replace(self.keys, contents_encryption_version=None)))
        encrypted = field(event, 100, 11)
        self.assertEqual(SecretBox(CONVERSATION_KEY).decrypt(encrypted), PLAINTEXT)
        self.assertNotIn(112, event)
        encoded = base64.b64encode(encrypted).decode().rstrip('=')
        self.verify(signature, (
            f'MessageCreateEvent,{MESSAGE_ID},100,100-200,7,{encoded},null,signature_version=11').encode())

    def test_non_ascii_message_is_utf8_and_not_changed(self):
        text = '你好 👋\n  preserved whitespace  '
        event, _ = self.unpack(self.prepare(text=text))
        plaintext = SecretBox(MESSAGE_KEY_V1).decrypt(field(event, 100, 11))
        contents = field(field(decode_struct(plaintext), 1, 12), 1, 12)
        self.assertEqual(field(contents, 1, 11).decode('utf-8'), text)

    def test_tampered_ciphertext_fails_authentication(self):
        event, _ = self.unpack(self.prepare())
        ciphertext = field(event, 100, 11)
        tampered = ciphertext[:-1] + bytes([ciphertext[-1] ^ 1])
        with self.assertRaises(CryptoError):
            SecretBox(MESSAGE_KEY_V1).decrypt(tampered)

    def test_prepared_result_matches_send_method_arguments(self):
        prepared = self.prepare()
        arguments = prepared.as_send_kwargs()
        self.assertEqual(set(arguments), {
            'conversation_id', 'message_id', 'conversation_token',
            'encoded_message_create_event', 'encoded_message_event_signature'})
        self.assertEqual(arguments['message_id'], MESSAGE_ID)
        self.assertEqual(arguments['conversation_token'], self.keys.conversation_token)
        for name in ('encoded_message_create_event', 'encoded_message_event_signature'):
            self.assertEqual(base64.b64encode(base64.b64decode(arguments[name], validate=True)).decode(),
                             arguments[name])

    def test_der_and_pem_string_private_keys_are_supported(self):
        der = self.private_key.private_bytes(
            serialization.Encoding.DER, serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption())
        for value in (der, self.pem.decode('ascii')):
            with self.subTest(format=type(value).__name__):
                _, signature = self.unpack(self.prepare(replace(self.keys, signing_key=value)))
                self.verify(signature, (
                    f'MessageCreateEvent,{MESSAGE_ID},100,100-200,7,{CONTENTS_V1},1,signature_version=11').encode())

    def test_browser_scalar_and_sdk_conversation_id_are_supported(self):
        keys = replace(self.keys, signing_key=(1).to_bytes(32, 'big'),
                       conversation_id='100:200')
        prepared = self.prepare(keys)
        event, signature = self.unpack(prepared)
        self.assertEqual(prepared.conversation_id, '100:200')
        self.assertEqual(SecretBox(MESSAGE_KEY_V1).decrypt(field(event, 100, 11)), PLAINTEXT)
        self.verify(signature, (
            f'MessageCreateEvent,{MESSAGE_ID},100,100:200,7,{CONTENTS_V1},1,signature_version=11').encode())
        # The group order is excluded, as is zero. Values are synthetic.
        p256_order = int('ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551', 16)
        for invalid_scalar in (0, p256_order, 2**256 - 1):
            with self.subTest(invalid_scalar=invalid_scalar):
                with self.assertRaisesRegex(ValueError, 'valid 32-byte P-256 scalar'):
                    prepare_text_message('hi', replace(keys, signing_key=invalid_scalar.to_bytes(32, 'big')))

    def test_generated_message_id_is_uuid_and_nonces_are_fresh(self):
        first = prepare_text_message('hi', self.keys)
        second = prepare_text_message('hi', self.keys)
        self.assertEqual(uuid.UUID(first.message_id).version, 4)
        self.assertNotEqual(first.message_id, second.message_id)
        self.assertNotEqual(first.encoded_message_create_event, second.encoded_message_create_event)

    def test_unknown_protocol_versions_fail_before_randomness(self):
        with patch('utils.xchat_crypto.os.urandom') as random:
            for value in (0, -1, 12, '11', True, None):
                with self.subTest(signature=value):
                    with self.assertRaisesRegex(ValueError, 'signature_version'):
                        prepare_text_message('hi', replace(self.keys, signature_version=value))
            for value in (0, -1, 2, '1', True):
                with self.subTest(contents=value):
                    with self.assertRaisesRegex(ValueError, 'contents_encryption_version'):
                        prepare_text_message('hi', replace(self.keys, contents_encryption_version=value))
            random.assert_not_called()

    def test_invalid_state_is_rejected_without_secret_in_error(self):
        invalid = {
            'conversation_key': (b'', bytes(31), bytes(33), 'SECRET_TEST_KEY'),
            'conversation_key_version': (-1, '07', 'bad', 2**63, True),
            'public_key_version': (-1, '1,2', True),
            'sender_id': ('', '100,200', '100\n', None),
            'conversation_id': ('', '100,200', '100\x00', None),
            'conversation_token': ('', ' ', 123),
            'signing_key': (b'', b'SECRET_INVALID_PRIVATE_KEY', 'not-a-key', '不是密钥'),
        }
        with patch('utils.xchat_crypto.os.urandom') as random:
            for name, values in invalid.items():
                for value in values:
                    with self.subTest(field=name, type=type(value).__name__):
                        with self.assertRaises(ValueError) as caught:
                            prepare_text_message('hi', replace(self.keys, **{name: value}))
                        self.assertNotIn('SECRET_', str(caught.exception))
            random.assert_not_called()

    def test_wrong_curve_and_empty_text_are_rejected(self):
        wrong_curve = ec.derive_private_key(1, ec.SECP384R1()).private_bytes(
            serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption())
        with self.assertRaisesRegex(ValueError, 'P-256'):
            prepare_text_message('hi', replace(self.keys, signing_key=wrong_curve))
        for text in ('', ' \n', None, b'hi'):
            with self.assertRaisesRegex(ValueError, 'text'):
                prepare_text_message(text, self.keys)

    def test_no_logging_and_private_material_not_in_repr(self):
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            prepared = self.prepare()
        self.assertEqual(stdout.getvalue() + stderr.getvalue(), '')
        for value in (repr(self.keys), repr(prepared)):
            self.assertNotIn('PRIVATE KEY', value)
            self.assertNotIn('SYNTHETIC_CONVERSATION_TOKEN', value)
            self.assertNotIn(repr(CONVERSATION_KEY), value)

    @unittest.skipUnless(shutil.which('node'), 'Node is optional for independent WebCrypto verification')
    def test_webcrypto_verifies_raw_signature_from_python(self):
        _, signature = self.unpack(self.prepare())
        public_key = self.private_key.public_key().public_bytes(
            serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        fixture = {
            'key': base64.b64encode(public_key).decode(),
            'signature': field(signature, 1, 11).decode(),
            'payload': f'MessageCreateEvent,{MESSAGE_ID},100,100-200,7,{CONTENTS_V1},1,signature_version=11',
        }
        script = """
const fs = require('node:fs');
const {webcrypto} = require('node:crypto');
(async () => {
  const x = JSON.parse(fs.readFileSync(0, 'utf8'));
  const key = await webcrypto.subtle.importKey('spki', Buffer.from(x.key, 'base64'),
    {name: 'ECDSA', namedCurve: 'P-256'}, false, ['verify']);
  const ok = await webcrypto.subtle.verify({name: 'ECDSA', hash: 'SHA-256'}, key,
    Buffer.from(x.signature, 'base64'), Buffer.from(x.payload));
  process.stdout.write(JSON.stringify({verified: ok}));
})().catch(() => { process.exitCode = 1; });
"""
        result = subprocess.run([shutil.which('node'), '-e', script], input=json.dumps(fixture),
                                text=True, capture_output=True, check=True, timeout=15)
        self.assertEqual(json.loads(result.stdout), {'verified': True})


class XChatKeyMaterialFileTests(unittest.TestCase):
    """Exercise real temporary files, containing synthetic key material only."""

    def setUp(self):
        directory = self.enterContext(tempfile.TemporaryDirectory(prefix='xchat-key-test-'))
        self.path = Path(directory) / 'synthetic-key-material.json'
        self.private_key = ec.derive_private_key(1, ec.SECP256R1())
        public = self.private_key.public_key().public_bytes(
            serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        self.document = {
            'sender_id': '100',
            'conversation_id': '100:200',
            'conversation_key_b64': base64.b64encode(CONVERSATION_KEY).decode(),
            'conversation_key_version': '7',
            'signing_key_b64': base64.b64encode((1).to_bytes(32, 'big')).decode(),
            'signing_public_key_b64': base64.b64encode(public).decode(),
            'public_key_version': '9',
            'signature_version': 11,
            'contents_encryption_version': 1,
            'conversation_token': 'SYNTHETIC_PRIVATE_TOKEN',
        }

    def write(self, document=None, *, mode=0o600, raw=None):
        if self.path.exists():
            self.path.unlink()
        with self.path.open('x', encoding='utf-8') as output:
            output.write(raw if raw is not None else json.dumps(
                self.document if document is None else document))
        self.path.chmod(mode)

    def test_0600_file_loads_and_prepares_valid_envelope(self):
        self.write()
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            keys = load_key_material(self.path)
            prepared = prepare_text_message('hi', keys, message_id=MESSAGE_ID)
        self.assertEqual(keys.sender_id, '100')
        self.assertEqual(keys.conversation_id, '100:200')
        self.assertEqual(keys.conversation_key, CONVERSATION_KEY)
        self.assertEqual(keys.signing_key, (1).to_bytes(32, 'big'))
        self.assertEqual(keys.conversation_key_version, '7')
        self.assertEqual(keys.public_key_version, '9')
        self.assertEqual(keys.signature_version, 11)
        self.assertEqual(keys.contents_encryption_version, 1)
        self.assertEqual(prepared.conversation_token, 'SYNTHETIC_PRIVATE_TOKEN')
        self.assertEqual(stdout.getvalue() + stderr.getvalue(), '')
        self.assertNotIn(self.document['signing_key_b64'], repr(keys))
        self.assertNotIn(self.document['conversation_key_b64'], repr(keys))
        self.assertNotIn('SYNTHETIC_PRIVATE_TOKEN', repr(keys))

    @unittest.skipUnless(os.name == 'posix', 'POSIX file modes only')
    def test_0644_file_is_rejected_before_reading_secrets(self):
        self.write(mode=0o644)
        with patch.object(Path, 'read_text', side_effect=AssertionError('Must not read insecure file')):
            with self.assertRaisesRegex(ValueError, '0600'):
                load_key_material(self.path)

    def test_malformed_json_or_wrong_json_shape_fails_without_leaking_data(self):
        for raw in ('{"signing_key_b64":"SECRET_MALFORMED_JSON"',
                    'null', '[]', '123', '"SECRET_NOT_AN_OBJECT"'):
            with self.subTest(case=raw[:1]):
                self.write(raw=raw)
                stdout, stderr = io.StringIO(), io.StringIO()
                with redirect_stdout(stdout), redirect_stderr(stderr):
                    with self.assertRaisesRegex(ValueError, 'Invalid X Chat key file') as caught:
                        load_key_material(self.path)
                self.assertNotIn('SECRET_', str(caught.exception))
                self.assertEqual(stdout.getvalue() + stderr.getvalue(), '')

    def test_missing_required_key_file_fields_are_rejected(self):
        for name in ('sender_id', 'conversation_id', 'conversation_key_b64',
                     'conversation_key_version', 'signing_key_b64',
                     'public_key_version', 'signature_version'):
            with self.subTest(field=name):
                document = dict(self.document)
                del document[name]
                self.write(document)
                with self.assertRaisesRegex(ValueError, 'Invalid X Chat key file'):
                    load_key_material(self.path)

    def test_public_private_key_mismatch_is_rejected(self):
        other_public = ec.derive_private_key(2, ec.SECP256R1()).public_key().public_bytes(
            serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        document = dict(self.document, signing_public_key_b64=base64.b64encode(other_public).decode())
        self.write(document)
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            with self.assertRaisesRegex(ValueError, 'public/private key mismatch') as caught:
                load_key_material(self.path)
        self.assertNotIn(self.document['signing_key_b64'], str(caught.exception))
        self.assertNotIn(document['signing_public_key_b64'], str(caught.exception))
        self.assertEqual(stdout.getvalue() + stderr.getvalue(), '')

    def test_invalid_key_base64_or_public_der_is_rejected(self):
        for name, value in (
                ('conversation_key_b64', 'SECRET_NOT_BASE64!'),
                ('signing_key_b64', 'SECRET_NOT_BASE64!'),
                ('signing_public_key_b64', 'SECRET_NOT_BASE64!'),
                ('signing_public_key_b64', base64.b64encode(b'SECRET_INVALID_DER').decode())):
            with self.subTest(field=name):
                self.write(dict(self.document, **{name: value}))
                with self.assertRaisesRegex(ValueError, 'Invalid X Chat key file') as caught:
                    load_key_material(self.path)
                self.assertNotIn('SECRET_', str(caught.exception))

    def test_oversized_key_file_and_directory_are_rejected(self):
        self.write(raw=' ' * 65537)
        with self.assertRaisesRegex(ValueError, '64 KiB'):
            load_key_material(self.path)
        with self.assertRaisesRegex(ValueError, 'regular file'):
            load_key_material(self.path.parent)

    def test_optional_fields_can_be_absent(self):
        document = dict(self.document)
        for name in ('signing_public_key_b64', 'contents_encryption_version', 'conversation_token'):
            del document[name]
        self.write(document)
        keys = load_key_material(self.path)
        self.assertIsNone(keys.contents_encryption_version)
        self.assertIsNone(keys.conversation_token)
        prepared = prepare_text_message('hi', keys, message_id=MESSAGE_ID)
        event = decode_base64_struct(prepared.encoded_message_create_event)
        self.assertEqual(SecretBox(CONVERSATION_KEY).decrypt(field(event, 100, 11)), PLAINTEXT)


if __name__ == '__main__':
    unittest.main()
